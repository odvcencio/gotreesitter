// lexExactSource is a small parser.c: state 0 accepts symbol 1 and goes to the
// end-token state on end of input; state 2 is the shape of an ADVANCE_MAP
// with key 0; state 3 is the guarded form that does not match at end of input.
// lexExactHeader is the standard lexer header (the grammar's own parser.h).
var lexExactHeader = lexexact.StandardHeader

const lexExactSource = `#include "tree_sitter/parser.h"
enum ts_symbol_identifiers {
  sym_word = 1,
  sym_num = 2,
};

static bool ts_lex(TSLexer *lexer, TSStateId state) {
  START_LEXER();
  eof = lexer->eof(lexer);
  switch (state) {
    case 0:
      ACCEPT_TOKEN(sym_word);
      if (eof) ADVANCE(1);
      if (lookahead == 'a') ADVANCE(2);
      if (('\t' <= lookahead && lookahead <= '\r') ||
          lookahead == ' ') SKIP(0);
      if (lookahead != 0 && lookahead != '\n') ADVANCE(3);
      END_STATE();
    case 1:
      ACCEPT_TOKEN(ts_builtin_sym_end);
      END_STATE();
    case 2:
      ACCEPT_TOKEN(sym_num);
      ADVANCE_MAP(
        0, 1,
        'b', 3,
      );
      END_STATE();
    case 3:
      ACCEPT_TOKEN(sym_num);
      if ((!eof && lookahead == 00)) ADVANCE(1);
      END_STATE();
    default:
      return false;
  }
}
`

// lexExactBlob imports the lex states of source into a blob, like ts2go does.
func lexExactBlob(t *testing.T, source string, edit func(*gts.Language)) []byte {
	t.Helper()
	dfa, err := ExtractLexDFA(source)
	if err != nil {
		t.Fatal(err)
	}
	entries := make([]LexStateEntry, len(dfa.States))
	for i, s := range dfa.States {
		entries[i] = LexStateEntry{Accept: s.Accept, HasAccept: s.HasAccept, EOF: s.EOF}
		for _, tr := range s.Transitions {
			entries[i].Transitions = append(entries[i].Transitions, LexTransitionEntry{Lo: tr.Lo, Hi: tr.Hi, Next: tr.Next, Skip: tr.Skip})
		}
	}
	lang := &gts.Language{LexStates: convertLexStates(entries)}
	if edit != nil {
		edit(lang)
	}
	blob, err := EncodeLanguageBlob(lang)
	if err != nil {
		t.Fatal(err)
	}
	return blob
}

func TestRunLexExactOnlyWritesRecordAndGoFile(t *testing.T) {
	dir := t.TempDir()
	blobPath := filepath.Join(dir, "demo.bin")
	blob := lexExactBlob(t, lexExactSource, nil)
	if err := os.WriteFile(blobPath, blob, 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "out")
	if err := os.MkdirAll(filepath.Join(out, "runtime"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, out, ""); err != nil {
		t.Fatal(err)
	}
	// The blob is not touched.
	after, _ := os.ReadFile(blobPath)
	if string(after) != string(blob) {
		t.Error("the blob was written")
	}
	data, err := os.ReadFile(filepath.Join(out, "runtime", "lex_exact", "demo.lexx"))
	if err != nil {
		t.Fatal(err)
	}
	rec, err := lexexact.Decode(data)
	if err != nil {
		t.Fatal(err)
	}
	if rec.BlobSHA256 != sha256.Sum256(blob) || rec.SourceSHA256 != sha256.Sum256([]byte(lexExactSource)) {
		t.Error("record hashes are wrong")
	}
	if err := rec.Validate(4, 0); err != nil {
		t.Error(err)
	}
	// The blob cannot tell these two states apart (both hold the range {0,0});
	// the record can.
	m := rec.Main
	if m.OnEOF[2] == 0 || m.OnEOF[3] != 0 || m.OnEOF[0] == 0 {
		t.Errorf("OnEOF = %v", m.OnEOF)
	}
	if m.OnInvalid[0] == 0 || m.OnInvalid[2] != 0 {
		t.Errorf("OnInvalid = %v", m.OnInvalid)
	}
	if m.Accept[0] != 2 || m.Accept[1] != 1 || m.Accept[2] != 3 {
		t.Errorf("Accept = %v", m.Accept)
	}
	gen, err := os.ReadFile(filepath.Join(out, "runtime", "demo_lex_exact_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "gen.go", gen, parser.AllErrors); err != nil {
		t.Errorf("generated Go does not parse: %v\n%s", err, gen)
	}
	for _, want := range []string{
		"//go:build !grammar_subset || grammar_subset_demo",
		"Code generated by cmd/ts2go",
		"//go:embed lex_exact/demo.lexx",
		"lexexact.MustHash(\"" + hexOf(sha256.Sum256(blob)) + "\")",
	} {
		if !strings.Contains(string(gen), want) {
			t.Errorf("generated Go lacks %q", want)
		}
	}
	if strings.Contains(string(gen), dir) {
		t.Error("generated Go holds a local path")
	}
	// Same input, same bytes.
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, out, ""); err != nil {
		t.Fatal(err)
	}
	again, _ := os.ReadFile(filepath.Join(out, "runtime", "lex_exact", "demo.lexx"))
	if string(again) != string(data) {
		t.Error("output differs between runs")
	}
}

func hexOf(h [32]byte) string {
	const digits = "0123456789abcdef"
	b := make([]byte, 0, 64)
	for _, c := range h {
		b = append(b, digits[c>>4], digits[c&15])
	}
	return string(b)
}

func TestRunLexExactOnlyRefusesBlobThatDiffersFromSource(t *testing.T) {
	dir := t.TempDir()
	blob := lexExactBlob(t, lexExactSource, func(l *gts.Language) {
		l.LexStates[0].Transitions[0].Hi++ // 'a' becomes 'a'..'b'
	})
	blobPath := filepath.Join(dir, "demo.bin")
	if err := os.WriteFile(blobPath, blob, 0o644); err != nil {
		t.Fatal(err)
	}
	err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, dir, "")
	if err == nil || !strings.Contains(err.Error(), "state 0") {
		t.Fatalf("err = %v", err)
	}
	if _, statErr := os.Stat(filepath.Join(dir, "lex_exact")); statErr == nil {
		t.Error("files were written after a failed check")
	}
}

func TestRunLexExactOnlyRefusesWrongStateCountAndAccept(t *testing.T) {
	dir := t.TempDir()
	blobPath := filepath.Join(dir, "demo.bin")
	short := lexExactBlob(t, lexExactSource, func(l *gts.Language) { l.LexStates = l.LexStates[:3] })
	os.WriteFile(blobPath, short, 0o644)
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, dir, ""); err == nil {
		t.Error("a blob with fewer states was accepted")
	}
	wrong := lexExactBlob(t, lexExactSource, func(l *gts.Language) { l.LexStates[2].AcceptToken = 1 })
	os.WriteFile(blobPath, wrong, 0o644)
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, dir, ""); err == nil || !strings.Contains(err.Error(), "accepts") {
		t.Errorf("wrong accept: err = %v", err)
	}
}

// A blob older than AcceptEOF lacks the end accept; the record holds it.
func TestRunLexExactOnlyBlobWithoutEndAccept(t *testing.T) {
	dir := t.TempDir()
	blob := lexExactBlob(t, lexExactSource, func(l *gts.Language) { l.LexStates[1].AcceptEOF = false })
	blobPath := filepath.Join(dir, "demo.bin")
	os.WriteFile(blobPath, blob, 0o644)
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, dir, ""); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(filepath.Join(dir, "lex_exact", "demo.lexx"))
	rec, err := lexexact.Decode(data)
	if err != nil {
		t.Fatal(err)
	}
	if rec.Main.Accept[1] != 1 {
		t.Errorf("Accept[1] = %d, want 1 (end token)", rec.Main.Accept[1])
	}
}

// The mode keeps the list of grammars that have a record: sorted, one name
// per line, no duplicates, and nothing written when the check fails.
func TestRunLexExactOnlyKeepsList(t *testing.T) {
	out := t.TempDir()
	if err := os.MkdirAll(filepath.Join(out, "runtime"), 0o755); err != nil {
		t.Fatal(err)
	}
	blobPath := filepath.Join(t.TempDir(), "demo.bin")
	if err := os.WriteFile(blobPath, lexExactBlob(t, lexExactSource, nil), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"zeta", "alpha", "zeta"} {
		if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, out, name); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(filepath.Join(out, "lex_exact_list.txt"))
	if err != nil {
		t.Fatal(err)
	}
	if want := lexExactListHeader + "alpha\nzeta\n"; string(got) != want {
		t.Errorf("list = %q, want %q", got, want)
	}
	bad := filepath.Join(t.TempDir(), "bad.bin")
	os.WriteFile(bad, lexExactBlob(t, lexExactSource, func(l *gts.Language) { l.LexStates[0].Transitions[0].Hi++ }), 0o644)
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, bad, out, "never"); err == nil {
		t.Fatal("a blob that differs from the source was accepted")
	}
	got, _ = os.ReadFile(filepath.Join(out, "lex_exact_list.txt"))
	if strings.Contains(string(got), "never") {
		t.Error("the list names a grammar whose check failed")
	}
}

// With -outdir naming the runtime folder itself, the files go there and the
// list is still the one at the catalog root, the file that the catalog test
// reads (grammars/lex_exact_list.txt), not a second list inside runtime.
func TestRunLexExactOnlyDirectRuntimeOutputKeepsRootList(t *testing.T) {
	root := t.TempDir()
	runtimeDir := filepath.Join(root, "runtime")
	if err := os.MkdirAll(runtimeDir, 0o755); err != nil {
		t.Fatal(err)
	}
	blobPath := filepath.Join(t.TempDir(), "demo.bin")
	if err := os.WriteFile(blobPath, lexExactBlob(t, lexExactSource, nil), 0o644); err != nil {
		t.Fatal(err)
	}
	// First through the root, then directly through the runtime folder.
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, root, "first"); err != nil {
		t.Fatal(err)
	}
	if err := RunLexExactOnly(lexExactSource, lexExactHeader, blobPath, runtimeDir, "second"); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(runtimeDir, "lex_exact_list.txt")); err == nil {
		t.Error("a second list was written inside the runtime folder")
	}
	got, err := os.ReadFile(filepath.Join(root, "lex_exact_list.txt"))
	if err != nil {
		t.Fatal(err)
	}
	if want := lexExactListHeader + "first\nsecond\n"; string(got) != want {
		t.Errorf("root list = %q, want %q", got, want)
	}
	for _, name := range []string{"first", "second"} {
		if _, err := os.Stat(filepath.Join(runtimeDir, "lex_exact", name+".lexx")); err != nil {
			t.Errorf("%s: record missing: %v", name, err)
		}
		if _, err := os.Stat(filepath.Join(runtimeDir, name+"_lex_exact_gen.go")); err != nil {
			t.Errorf("%s: generated file missing: %v", name, err)
		}
	}
}
