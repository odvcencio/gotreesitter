func TestDiscoverGeneratedOutputsRejectsUnsafeEntries(t *testing.T) {
	tests := []struct {
		name string
		make func(t *testing.T, dir string, path string) error
		want string
	}{
		{
			name: "symlink",
			make: func(t *testing.T, dir, path string) error {
				t.Helper()
				target := filepath.Join(dir, "owned-target.go")
				if err := os.WriteFile(target, []byte(renderGeneratedFile("go")), 0o644); err != nil {
					return err
				}
				return os.Symlink(target, path)
			},
			want: "is a symlink",
		},
		{
			name: "directory",
			make: func(_ *testing.T, _ string, path string) error { return os.Mkdir(path, 0o755) },
			want: "is a directory",
		},
		{
			name: "named pipe",
			make: func(_ *testing.T, _ string, path string) error {
				return exec.Command("mkfifo", path).Run()
			},
			want: "not a regular file",
		},
		{
			name: "unowned content",
			make: func(_ *testing.T, _ string, path string) error {
				return os.WriteFile(path, []byte("package grammars\n"), 0o644)
			},
			want: "does not match the generator template",
		},
		{
			name: "malformed generated content",
			make: func(_ *testing.T, _ string, path string) error {
				contents := strings.Replace(renderGeneratedFile("go"), "registerSubsetEmbeddedBlob", "registerWrongBlob", 1)
				return os.WriteFile(path, []byte(contents), 0o644)
			},
			want: "does not match the generator template",
		},
		{
			name: "invalid name",
			make: func(_ *testing.T, _ string, path string) error {
				return os.WriteFile(path, nil, 0o644)
			},
			want: "invalid build-tag/identifier suffix",
		},
		{
			name: "invalid suffix",
			make: func(_ *testing.T, _ string, path string) error {
				return os.WriteFile(path, nil, 0o644)
			},
			want: "has invalid name",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			name := prefix + "go.go"
			if tt.name == "invalid name" {
				name = prefix + "bad-name.go"
			}
			if tt.name == "invalid suffix" {
				name = prefix + "go.txt"
			}
			path := filepath.Join(dir, name)
			if err := tt.make(t, dir, path); err != nil {
				t.Skipf("cannot create %s output fixture: %v", tt.name, err)
			}
			_, _, err := discoverGeneratedOutputs(dir)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("discoverGeneratedOutputs() error = %v, want %q", err, tt.want)
			}
		})
	}
}

