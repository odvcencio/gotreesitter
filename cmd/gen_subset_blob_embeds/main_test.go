func TestDiscoverBlobLanguagesRejectsSourceTypes(t *testing.T) {
	tests := []struct {
		name string
		make func(string) error
		want string
	}{
		{
			name: "directory",
			make: func(path string) error { return os.Mkdir(path, 0o755) },
			want: "is a directory",
		},
		{
			name: "symlink",
			make: func(path string) error {
				target := path + ".target"
				if err := os.WriteFile(target, nil, 0o644); err != nil {
					return err
				}
				return os.Symlink(target, path)
			},
			want: "is a symlink",
		},
		{
			name: "named pipe",
			make: func(path string) error {
				return exec.Command("mkfifo", path).Run()
			},
			want: "not a regular file",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := tt.make(filepath.Join(dir, "go.bin")); err != nil {
				t.Skipf("cannot create %s source fixture: %v", tt.name, err)
			}
			_, err := discoverBlobLanguages(dir)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("discoverBlobLanguages() error = %v, want %q", err, tt.want)
			}
		})
	}
}

