func TestWriteGeneratedEmbedsStagesBeforeMutation(t *testing.T) {
	dir := t.TempDir()
	paths := map[string]string{}
	for _, lang := range []string{"go", "python", "rust"} {
		path := filepath.Join(dir, prefix+lang+".go")
		if err := os.WriteFile(path, []byte(renderGeneratedFile(lang)), 0o644); err != nil {
			t.Fatal(err)
		}
		paths[lang] = path
	}
	before := make(map[string]string, len(paths))
	for lang, path := range paths {
		contents, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		before[lang] = string(contents)
	}

	stager := func(dir, lang string, contents []byte) (string, error) {
		f, err := os.CreateTemp(dir, ".h2-stage-*")
		if err != nil {
			return "", err
		}
		path := f.Name()
		if _, err := f.Write(contents); err != nil {
			_ = f.Close()
			_ = os.Remove(path)
			return path, err
		}
		if err := f.Close(); err != nil {
			_ = os.Remove(path)
			return path, err
		}
		if lang == "python" {
			return path, errors.New("injected staging failure")
		}
		return path, nil
	}

	err := writeGeneratedEmbedsWithStager(dir, []string{"go", "python"}, stager)
	if err == nil || !strings.Contains(err.Error(), "injected staging failure") {
		t.Fatalf("writeGeneratedEmbedsWithStager() error = %v, want staging failure", err)
	}
	for lang, path := range paths {
		contents, readErr := os.ReadFile(path)
		if readErr != nil {
			t.Fatalf("output %s read after staging failure: %v", lang, readErr)
		}
		if string(contents) != before[lang] {
			t.Errorf("output %s changed before all files were staged", lang)
		}
	}
	entries, readErr := os.ReadDir(dir)
	if readErr != nil {
		t.Fatal(readErr)
	}
	for _, entry := range entries {
		if strings.HasPrefix(entry.Name(), ".h2-stage-") {
			t.Errorf("staged temporary %q remained after failure", entry.Name())
		}
	}
}

