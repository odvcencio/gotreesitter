func TestDiscoverBlobLanguagesSortsAndFilters(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{"python.bin", "README", "go.bin"} {
		if err := os.WriteFile(filepath.Join(dir, name), nil, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Mkdir(filepath.Join(dir, "ignored-directory"), 0o755); err != nil {
		t.Fatal(err)
	}

	got, err := discoverBlobLanguages(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"go", "python"}
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Fatalf("discoverBlobLanguages() = %v, want %v", got, want)
	}
}

