func TestValidateGeneratedOutputs(t *testing.T) {
	tests := []struct {
		name    string
		blobs   []string
		outputs []string
		mutate  func(t *testing.T, path string)
		wantErr []string
	}{
		{
			name:    "matching source and output sets",
			blobs:   []string{"go", "python"},
			outputs: []string{"go", "python"},
		},
		{
			name:    "missing output",
			blobs:   []string{"go", "python"},
			outputs: []string{"go"},
			wantErr: []string{"missing generated file", "z_subset_blob_embed_python.go"},
		},
		{
			name:    "stale output",
			blobs:   []string{"go"},
			outputs: []string{"go", "python"},
			wantErr: []string{"stale generated file", "z_subset_blob_embed_python.go"},
		},
		{
			name:    "modified output",
			blobs:   []string{"go"},
			outputs: []string{"go"},
			mutate: func(t *testing.T, path string) {
				t.Helper()
				if err := os.WriteFile(path, []byte("modified\n"), 0o644); err != nil {
					t.Fatal(err)
				}
			},
			wantErr: []string{"does not match the generator template", "z_subset_blob_embed_go.go"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			blobDir := filepath.Join(root, "grammar_blobs")
			outDir := filepath.Join(root, "grammars")
			if err := os.MkdirAll(blobDir, 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.MkdirAll(outDir, 0o755); err != nil {
				t.Fatal(err)
			}
			for _, lang := range tt.blobs {
				if err := os.WriteFile(filepath.Join(blobDir, lang+".bin"), nil, 0o644); err != nil {
					t.Fatal(err)
				}
			}
			for _, lang := range tt.outputs {
				path := filepath.Join(outDir, prefix+lang+".go")
				if err := os.WriteFile(path, []byte(renderGeneratedFile(lang)), 0o644); err != nil {
					t.Fatal(err)
				}
				if tt.mutate != nil && lang == "go" {
					tt.mutate(t, path)
				}
			}

			langs, err := discoverBlobLanguages(blobDir)
			if err != nil {
				t.Fatal(err)
			}
			err = validateGeneratedOutputs(outDir, langs)
			if len(tt.wantErr) == 0 {
				if err != nil {
					t.Fatalf("validateGeneratedOutputs() error = %v", err)
				}
				return
			}
			if err == nil {
				t.Fatal("validateGeneratedOutputs() error = nil, want validation failure")
			}
			for _, want := range tt.wantErr {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("validation error %q does not contain %q", err, want)
				}
			}
		})
	}
}

