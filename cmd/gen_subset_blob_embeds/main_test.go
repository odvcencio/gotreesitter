func TestCheckValidationIsNonMutating(t *testing.T) {
	dir := t.TempDir()
	owned := filepath.Join(dir, prefix+"go.go")
	stale := filepath.Join(dir, prefix+"python.go")
	if err := os.WriteFile(owned, []byte(renderGeneratedFile("go")), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(stale, []byte(renderGeneratedFile("python")), 0o644); err != nil {
		t.Fatal(err)
	}
	beforeOwned, err := os.ReadFile(owned)
	if err != nil {
		t.Fatal(err)
	}
	beforeStale, err := os.ReadFile(stale)
	if err != nil {
		t.Fatal(err)
	}

	err = validateGeneratedOutputs(dir, []string{"go"})
	if err == nil || !strings.Contains(err.Error(), "stale generated file") {
		t.Fatalf("validateGeneratedOutputs() error = %v, want stale-output error", err)
	}
	afterOwned, readErr := os.ReadFile(owned)
	if readErr != nil {
		t.Fatal(readErr)
	}
	afterStale, readErr := os.ReadFile(stale)
	if readErr != nil {
		t.Fatal(readErr)
	}
	if string(afterOwned) != string(beforeOwned) || string(afterStale) != string(beforeStale) {
		t.Fatal("check validation changed an output")
	}
}

func TestGeneratedOutputErrorsAreDeterministic(t *testing.T) {
	dir := t.TempDir()
	for _, lang := range []string{"b", "a"} {
		path := filepath.Join(dir, prefix+lang+".go")
		if err := os.WriteFile(path, []byte("not generated"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	_, _, err := discoverGeneratedOutputs(dir)
	if err == nil {
		t.Fatal("discoverGeneratedOutputs() error = nil, want malformed-output errors")
	}
	a := strings.Index(err.Error(), prefix+"a.go")
	b := strings.Index(err.Error(), prefix+"b.go")
	if a < 0 || b < 0 || a >= b {
		t.Fatalf("output errors are not sorted: %q", err)
	}
}
