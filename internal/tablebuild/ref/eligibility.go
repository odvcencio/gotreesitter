package ref

import (
	"fmt"
	"regexp"
	"strings"
)

// Eligibility is the result of comparing a parser.c that the generator wrote
// with the pinned parser.c, apart from the version comment on the first line.
type Eligibility struct {
	Equal            bool
	PinnedVersion    string // from the version comment; "(no version)" when it names none, "" when there is no comment
	GeneratedVersion string
	Line             int    // first differing line, 1-based, after the version comment
	Table            string // the first declaration whose text differs
	Pinned           []string
	Generated        []string // up to three lines of that declaration from its first difference
	Tables           []string // every declaration whose text differs, in pinned order, then those only in the generated file
}

// reVersionComment matches the first line the generator writes: v0.25 adds
// its version ("by tree-sitter v0.25.8"), v0.27.1 writes none.
var reVersionComment = regexp.MustCompile(`^/\* Automatically @?generated by tree-sitter(?: (v?\S+))? \*/$`)

// reDecl matches a line that starts a top-level declaration of a parser.c.
var reDecl = regexp.MustCompile(`^(#define \w+|#include .*|#pragma .*|#if.*|#endif.*|enum \w*|typedef .*|static .*|const .*|TS_PUBLIC .*|extern .*|bool .*|void .*|unsigned .*|struct .*)`)

var reDeclName = regexp.MustCompile(`(\w+)\s*(?:\[|\()`)

func stripVersion(text string) (string, []string) {
	lines := strings.Split(text, "\n")
	if len(lines) > 0 {
		if m := reVersionComment.FindStringSubmatch(lines[0]); m != nil {
			if m[1] == "" {
				return "(no version)", lines[1:]
			}
			return m[1], lines[1:]
		}
	}
	return "", lines
}

// declName is a short name for a declaration line: the array or function
// name, or the line itself.
func declName(l string) string {
	if f := strings.Fields(l); len(f) >= 2 && (f[0] == "#define" || f[0] == "enum") {
		return f[0] + " " + f[1]
	}
	if m := reDeclName.FindStringSubmatch(l); m != nil {
		return m[1]
	}
	return strings.TrimSpace(l)
}

// blocks splits a parser.c into its top-level declarations, keyed by name;
// a repeated name gets a "#n" suffix.
func blocks(lines []string) (order []string, text map[string]string) {
	text = map[string]string{}
	seen := map[string]int{}
	cur := "(head)"
	order = append(order, cur)
	var b strings.Builder
	flush := func() { text[cur] = b.String(); b.Reset() }
	for _, l := range lines {
		if reDecl.MatchString(l) {
			flush()
			name := declName(l)
			seen[name]++
			if seen[name] > 1 {
				name = fmt.Sprintf("%s#%d", name, seen[name])
			}
			cur = name
			order = append(order, cur)
		}
		b.WriteString(l)
		b.WriteByte('\n')
	}
	flush()
	return order, text
}

// CompareGenerated compares a generated parser.c with the pinned one.
func CompareGenerated(pinned, generated []byte) Eligibility {
	var e Eligibility
	var pl, gl []string
	e.PinnedVersion, pl = stripVersion(string(pinned))
	e.GeneratedVersion, gl = stripVersion(string(generated))
	i := 0
	for i < len(pl) && i < len(gl) && pl[i] == gl[i] {
		i++
	}
	if i == len(pl) && i == len(gl) {
		e.Equal = true
		return e
	}
	e.Line = i + 1
	po, pt := blocks(pl)
	genOrder, gt := blocks(gl)
	for _, n := range po {
		if g, ok := gt[n]; !ok || g != pt[n] {
			e.Tables = append(e.Tables, n)
		}
	}
	for _, n := range genOrder {
		if _, ok := pt[n]; !ok {
			e.Tables = append(e.Tables, n+" (generated only)")
		}
	}
	// Name the first declaration that differs; the lines before the first
	// declaration (blank lines left by the version comment) count only when
	// nothing else differs.
	e.Table = "(head)"
	for _, n := range e.Tables {
		if n != "(head)" {
			e.Table = n
			break
		}
	}
	name := strings.TrimSuffix(e.Table, " (generated only)")
	a, b := strings.Split(pt[name], "\n"), strings.Split(gt[name], "\n")
	k := 0
	for k < len(a) && k < len(b) && a[k] == b[k] {
		k++
	}
	for j := k; j < k+3; j++ {
		if j < len(a) && pt[name] != "" {
			e.Pinned = append(e.Pinned, a[j])
		}
		if j < len(b) && gt[name] != "" {
			e.Generated = append(e.Generated, b[j])
		}
	}
	return e
}

// String is one line for the eligibility table, then the first lines.
func (e Eligibility) String() string {
	if e.Equal {
		return fmt.Sprintf("equal apart from the version comment (pinned %q, generated %q)", e.PinnedVersion, e.GeneratedVersion)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "differs (pinned %q, generated %q): first line %d; first declaration %s; %d declarations differ: %s",
		e.PinnedVersion, e.GeneratedVersion, e.Line, e.Table, len(e.Tables), strings.Join(e.Tables, ", "))
	for _, l := range e.Pinned {
		fmt.Fprintf(&b, "\n  pinned:    %s", clip(l))
	}
	for _, l := range e.Generated {
		fmt.Fprintf(&b, "\n  generated: %s", clip(l))
	}
	return b.String()
}
