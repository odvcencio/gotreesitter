func TestCanonicalRangesFollowFirstMatch(t *testing.T) {
	ts := []gts.LexTransition{
		{Lo: 'a', Hi: 'c', NextState: 1},
		{Lo: 'b', Hi: 'z', NextState: 2}, // b and c go to 1: the first match wins
		{Lo: '0', Hi: '4', NextState: 3, Skip: true},
		{Lo: '5', Hi: '9', NextState: 3, Skip: true}, // merges with the range before
	}
	want := []seg{{'0', '9', 3, true}, {'a', 'c', 1, false}, {'d', 'z', 2, false}}
	if got := canonicalRanges(ts); !reflect.DeepEqual(got, want) {
		t.Fatalf("canonicalRanges = %v, want %v", got, want)
	}
	split := []gts.LexTransition{{Lo: 'a', Hi: 'b', NextState: 1}, {Lo: 'c', Hi: 'c', NextState: 1}}
	if got := canonicalRanges(split); !reflect.DeepEqual(got, []seg{{'a', 'c', 1, false}}) {
		t.Fatalf("adjacent ranges not merged: %v", got)
	}
}

func TestGrammarRecordsKeepFileOrder(t *testing.T) {
	g := `{"$schema":"x","name":"t","word":"id","rules":{"b":{"type":"STRING","value":"\u0000"},"a":{"value":"y","type":"PATTERN"}},"extras":[{"type":"PATTERN","value":"\\s"},{"type":"SYMBOL","name":"c"}],"conflicts":[],"precedences":[[1.50,"x"]]}`
	got, err := GrammarRecords([]byte(g))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"L0\tname\t\"t\"",
		"L0\tword\t\"id\"",
		"L0\trule\t\"b\"\t{\"type\":\"STRING\",\"value\":\"\\x00\"}",
		"L0\trule\t\"a\"\t{\"value\":\"y\",\"type\":\"PATTERN\"}",
		"L0\textras\t0\t{\"type\":\"PATTERN\",\"value\":\"\\\\s\"}",
		"L0\textras\t1\t{\"type\":\"SYMBOL\",\"name\":\"c\"}",
		"L0\tprecedences\t0\t[1.50,\"x\"]",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("GrammarRecords:\n got %q\nwant %q", got, want)
	}
	nt, err := NodeTypeRecords([]byte(`[{"type":"a","named":true},{"type":"b","named":false,"fields":{}}]`))
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"L1\tnode-type\t{\"type\":\"a\",\"named\":true}", "L1\tnode-type\t{\"type\":\"b\",\"named\":false,\"fields\":{}}"}; !reflect.DeepEqual(nt, want) {
		t.Fatalf("NodeTypeRecords = %q", nt)
	}
}

func TestCompareGeneratedNamesTheTable(t *testing.T) {
	pinned := "/* Automatically @generated by tree-sitter v0.25.8 */\n\n#define STATE_COUNT 3\n\nstatic const TSStateId ts_primary_state_ids[STATE_COUNT] = {\n  [0] = 0,\n  [1] = 1,\n};\n\nstatic bool ts_lex(TSLexer *lexer, TSStateId state) {\n  return false;\n}\n"
	same := strings.Replace(pinned, "v0.25.8", "v0.27.1", 1)
	if e := CompareGenerated([]byte(pinned), []byte(same)); !e.Equal || e.PinnedVersion != "v0.25.8" || e.GeneratedVersion != "v0.27.1" {
		t.Fatalf("version comment only: %+v", e)
	}
	other := strings.Replace(same, "[1] = 1,", "[1] = 0,", 1)
	e := CompareGenerated([]byte(pinned), []byte(other))
	if e.Equal || e.Table != "ts_primary_state_ids" || e.Line != 6 || e.Pinned[0] != "  [1] = 1," || e.Generated[0] != "  [1] = 0," {
		t.Fatalf("one entry differs: %+v", e)
	}
	if !reflect.DeepEqual(e.Tables, []string{"ts_primary_state_ids"}) {
		t.Fatalf("differing declarations %v", e.Tables)
	}
	// v0.27.1 writes the comment without a version.
	bare := strings.Replace(same, " v0.27.1", "", 1)
	if e := CompareGenerated([]byte(pinned), []byte(bare)); !e.Equal || e.GeneratedVersion != "(no version)" {
		t.Fatalf("comment without a version: %+v", e)
	}
	// A pinned file without a version comment (written before the comment existed).
	if e := CompareGenerated([]byte(strings.SplitN(pinned, "\n", 2)[1]), []byte(same)); !e.Equal || e.PinnedVersion != "" {
		t.Fatalf("no version comment: %+v", e)
	}
}

func TestDigestFileRoundTrip(t *testing.T) {
	lines := []string{line("L4", "state", "0", "1=A1[S1]"), line("L0", "name", `"t"`)}
	f := &DigestFile{Grammar: "t", Commit: "c", Generator: "g", Eligible: true, Sources: map[string]string{"parser.c": "x"}, Sections: SectionDigests(lines)}
	b := f.Marshal()
	path := t.TempDir() + "/digests.json"
	if err := os.WriteFile(path, b, 0o644); err != nil {
		t.Fatal(err)
	}
	back, err := ReadDigestFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(back, f) {
		t.Fatalf("round trip:\n%s\n%+v", b, back)
	}
	if string(back.Marshal()) != string(b) {
		t.Fatal("Marshal is not stable")
	}
}
