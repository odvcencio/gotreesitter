func TestCompareNamesFirstField(t *testing.T) {
	ref := []string{
		line("L4", "counts", "states=2"),
		line("L4", "state", "0", "1=A1[S1]", "2=A3[R4/1/0/0]"),
		line("L4", "state", "1", "1=A1[S1]"),
		line("L5", "state", "0", "lex=0"),
	}
	port := append([]string(nil), ref...)
	port[2] = line("L4", "state", "1", "1=A5[S1]")
	port[3] = line("L5", "state", "0", "lex=3")
	d := Compare(port, ref)
	if d == nil {
		t.Fatal("no difference found")
	}
	if d.Section != "L4 state" || d.Index != 1 || d.Field != 3 || d.PortField != "1=A5[S1]" || d.RefField != "1=A1[S1]" {
		t.Fatalf("divergence %+v", d)
	}
	if s := d.String(); !strings.Contains(s, `field 3: port "1=A5[S1]", reference "1=A1[S1]"`) {
		t.Fatalf("String() = %s", s)
	}
	if Compare(ref, ref) != nil {
		t.Fatal("equal sets differ")
	}
	// A record only one side has.
	if d := Compare(ref[:3], ref); d == nil || d.Section != "L5 state" || d.Port != "" || d.PortCount != 0 {
		t.Fatalf("missing section: %+v", d)
	}
	// The digest form names the same record.
	d = CompareDigests(port, SectionDigests(ref))
	if d == nil || d.Section != "L4 state" || d.Index != 1 || d.RefDigest != Digest(ref[2]) || d.Field != -1 {
		t.Fatalf("digest divergence %+v", d)
	}
	if CompareDigests(ref, SectionDigests(ref)) != nil {
		t.Fatal("equal digests differ")
	}
}

