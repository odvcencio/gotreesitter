// Package certgen writes internal/ccore/certified/gen.go from the
// certificate records. The file lists which grammar blobs the ccore parser
// serves by default and for which modes. A blob is named by the SHA-256 of
// its bytes (Language.GrammarBlobSHA256), never by the language name.
//
// The records live in testdata/ccore_certificates.json of the root package.
// A root test renders them with Render and compares the result with the
// checked-in file, so the file cannot be edited by hand. go run ./cmd/ccorecert
// writes it.
package certgen

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/odvcencio/gotreesitter/internal/ccore/certified"
)

// The generator accepts the same mode bits as the runtime.
const (
	Fresh      = certified.Fresh
	Recover    = certified.Recover
	Scan       = certified.Scan
	Incr       = certified.Incr
	Ranges     = certified.Ranges
	Forest     = certified.Forest
	knownModes = Fresh | Recover | Scan | Incr | Ranges | Forest
)

// Record is one certificate: a blob, the modes it is certified for, and the
// digest of the evidence (free text: for example the name of the equality run).
type Record struct {
	BlobSHA256 string // 64 hex characters
	Modes      uint8
	Digest     string // free text, written into a comment
	// Scanner is the Go type of the language's external scanner as fmt's %T
	// prints it ("" for a language without one). The certificate holds only for
	// that scanner; a language with another one is declined.
	Scanner string
	// Checked lists the root-only language fields (ImmediateTokens,
	// ZeroWidthTokens, LayoutFallbackLexState, AfterWhitespaceLexState) that the
	// equality tests compared with pinned C for this blob. A language that sets
	// a field not listed here is declined.
	Checked []string
	// ConfigSHA256 is the effective-configuration hash of the blob's loaded
	// language (64 hex characters), which cmd/ccorecert
	// computes. The route computes the same hash when it first binds a language
	// value and declines a language that differs.
	ConfigSHA256 string
	// Providers lists the scan providers (internal/ccore ScanProvider) whose
	// answers were compared with pinned C for this blob, by identity ("table-v1").
	// A token source that carries one of them is served by the core. An omitted
	// list grants none.
	Providers []string `json:",omitempty"`
}

// knownProviders are the provider identities a record may list.
var knownProviders = map[string]bool{"table-v1": true}

// Parse reads the records of testdata/ccore_certificates.json.
func Parse(raw []byte) ([]Record, error) {
	var recs []Record
	if err := json.Unmarshal(raw, &recs); err != nil {
		return nil, err
	}
	return recs, nil
}

// Render returns the text of internal/ccore/certified/gen.go for the records. With no
// records the table is empty. The order is by blob, so the output does not
// depend on the order of the records.
func Render(recs []Record) ([]byte, error) {
	sorted := append([]Record(nil), recs...)
	sort.Slice(sorted, func(i, j int) bool {
		return strings.ToLower(sorted[i].BlobSHA256) < strings.ToLower(sorted[j].BlobSHA256)
	})
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/ccorecert from testdata/ccore_certificates.json; DO NOT EDIT.\n\n")
	b.WriteString("package certified\n\n")
	b.WriteString("// Blobs maps the SHA-256 of a grammar blob to its certificate: the\n")
	b.WriteString("// modes (bits of Fresh, Recover, Scan, Incr, Ranges) for which internal/ccore is certified to serve it\n")
	b.WriteString("// by default, the external scanner type it was checked with, and the root-only\n")
	b.WriteString("// fields it was compared with pinned C for.\n")
	if len(sorted) == 0 {
		b.WriteString("// It is empty: no grammar is certified.\n")
		b.WriteString("var Blobs = map[[32]byte]Cert{}\n")
		return b.Bytes(), nil
	}
	b.WriteString("var Blobs = makeBlobMap(generatedBlobs[:])\n\n")
	b.WriteString("var generatedBlobs = [...]blobEntry{\n")
	seen := map[[32]byte]bool{}
	for _, r := range sorted {
		raw, err := hex.DecodeString(r.BlobSHA256)
		if err != nil || len(raw) != 32 {
			return nil, fmt.Errorf("certgen: bad blob hash %q", r.BlobSHA256)
		}
		var key [32]byte
		copy(key[:], raw) // the decoded hash is the identity: upper and lower case spell one blob
		if seen[key] {
			return nil, fmt.Errorf("certgen: blob %s listed twice", r.BlobSHA256)
		}
		seen[key] = true
		cfg, cerr := hex.DecodeString(r.ConfigSHA256)
		if cerr != nil || len(cfg) != 32 {
			return nil, fmt.Errorf("certgen: blob %s has no configuration hash", r.BlobSHA256)
		}
		if r.Modes&(Fresh|Recover) != Fresh|Recover {
			return nil, fmt.Errorf("certgen: blob %s lacks the fresh and recover modes", r.BlobSHA256)
		}
		if r.Modes&^knownModes != 0 {
			return nil, fmt.Errorf("certgen: blob %s has unknown mode bits %#x", r.BlobSHA256, r.Modes)
		}
		for _, id := range r.Providers {
			if !knownProviders[id] {
				return nil, fmt.Errorf("certgen: blob %s lists unknown provider %q", r.BlobSHA256, id)
			}
		}
		fmt.Fprintf(&b, "\t// certificate digest: %s\n\t{[32]byte{", strings.Map(func(c rune) rune {
			if c == '\n' || c == '\r' {
				return ' '
			}
			return c
		}, r.Digest))
		for i, c := range raw {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "0x%02x", c)
		}
		fmt.Fprintf(&b, "}, Cert{Modes: %d, Scanner: %q, Config: [32]byte{", r.Modes, r.Scanner)
		for i, c := range cfg {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "0x%02x", c)
		}
		b.WriteString("}")
		if len(r.Checked) > 0 {
			ck := append([]string(nil), r.Checked...)
			sort.Strings(ck)
			fmt.Fprintf(&b, ", Checked: []string{")
			for i, c := range ck {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", c)
			}
			b.WriteString("}")
		}
		if len(r.Providers) > 0 {
			ids := append([]string(nil), r.Providers...)
			sort.Strings(ids)
			fmt.Fprintf(&b, ", Providers: []string{")
			for i, id := range ids {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", id)
			}
			b.WriteString("}")
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}
