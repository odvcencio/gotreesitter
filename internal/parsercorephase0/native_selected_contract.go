// NativeSelectedSnapshotContract limits public-view qualification to table
// identities whose result normalization is implemented by the indexed builder.
// Grammar regeneration and unrelated normalizers must qualify independently.
func NativeSelectedSnapshotContract(identity [32]byte) bool {
	return NativeSelectedSnapshotDefaultContract(identity) ||
		identity == [32]byte{0x9a, 0xc3, 0x7a, 0x32, 0x6b, 0xe7, 0xa4, 0xf4, 0x29, 0x7e, 0xfa, 0x6e, 0x43, 0xba, 0x00, 0x31, 0x7c, 0x59, 0x59, 0xe7, 0xb4, 0x90, 0x9c, 0x92, 0x62, 0x04, 0x3d, 0x40, 0x8f, 0x28, 0x4b, 0x30}
}

